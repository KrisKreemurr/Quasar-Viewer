#!/usr/bin/env python3
"""#703: list every view class that defines its own draw(), for the classic RmlUi presenter.

A view whose dynamic class is in this list draws something its base class does not, so the
RmlUi presenter may only show it when it has a presenter for exactly that class; otherwise
its whole top-level view stays on the LLView renderer. Regenerate after adding draw():
    python3 scripts/ui/gen_rmlui_drawlist.py
"""
import pathlib, re, sys

root = pathlib.Path(__file__).resolve().parents[2] / "indra"
pat = re.compile(r"^\s*void\s+(?:[A-Za-z_][A-Za-z0-9_]*::)*([A-Za-z_][A-Za-z0-9_]*)::draw\s*\(\s*\)", re.M)  # nested: innermost
names = set()
for sub in ("llui", "newview"):
    for p in (root / sub).rglob("*.cpp"):
        names.update(pat.findall(p.read_text(errors="replace")))
out = root / "newview" / "llrmluiclassic_drawlist.inc"
body = "".join(f'    "{n}",\n' for n in sorted(names))
text = ("// Generated by scripts/ui/gen_rmlui_drawlist.py: view classes that define draw().\n"
        "// Sorted (binary-searched). Do not edit by hand.\n" + body)
if "--check" in sys.argv:
    sys.exit(0 if out.exists() and out.read_text() == text else 1)
out.write_text(text)
print(f"{len(names)} classes -> {out}")
