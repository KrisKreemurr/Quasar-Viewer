#!/usr/bin/env python3
"""Compiles the Vulkan presenter's shaders (indra/llwindow/vkshaders/*.comp, *.vert, *.tesc, *.tese, *.frag) to SPIR-V and writes them into
indra/llwindow/qlvulkanshaders.h as arrays, so the viewer's build needs no shader compiler.

    python3 scripts/code_tools/build_vulkan_shaders.py --glslang /path/to/glslang

Run it after changing a shader there, or newview's deferred/CASF.glsl, which qlcas.comp takes its filter from.
"""
import argparse
import os
import struct
import subprocess
import sys
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "indra", "llwindow", "vkshaders")
OUT = os.path.join(ROOT, "indra", "llwindow", "qlvulkanshaders.h")
CASF = os.path.join(ROOT, "indra", "newview", "app_settings", "shaders", "class1", "deferred", "CASF.glsl")


def cas_body():
    text = open(CASF, encoding="utf-8").read()
    start = text.index("#ifndef SHADER_PORTABILITY")
    return text[start:]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--glslang", default="glslang")
    args = parser.parse_args()

    shaders = sorted(f for f in os.listdir(SRC) if f.endswith((".comp", ".vert", ".tesc", ".tese", ".frag")))
    lines = [
        "// Generated by scripts/code_tools/build_vulkan_shaders.py from indra/llwindow/vkshaders. Do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
    ]
    for name in shaders:
        source = "\n".join(cas_body() if line.strip() == "@CAS_BODY@" else line
                           for line in open(os.path.join(SRC, name), encoding="utf-8").read().split("\n"))
        with tempfile.TemporaryDirectory() as tmp:
            src = os.path.join(tmp, name)
            spv = os.path.join(tmp, name + ".spv")
            open(src, "w", encoding="utf-8").write(source)
            result = subprocess.run([args.glslang, "-V", "--target-env", "vulkan1.1", src, "-o", spv],
                                    capture_output=True, text=True)
            if result.returncode != 0:
                sys.stderr.write(result.stdout + result.stderr)
                return 1
            data = open(spv, "rb").read()
        words = struct.unpack("<%dI" % (len(data) // 4), data)
        ident = "ql_spv_" + name.replace(".", "_")
        lines.append("static const uint32_t %s[] = {" % ident)
        for i in range(0, len(words), 8):
            lines.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
        lines.append("};")
        lines.append("")
        print("%s: %d words" % (name, len(words)))
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
