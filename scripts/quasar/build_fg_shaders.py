#!/usr/bin/env python3
"""Compile Quasar's frame generation shaders and embed the SPIR-V in a header.

usage: build_fg_shaders.py <glslangValidator or glslang>
The header (indra/newview/vkgfx/qlframegen_spv.h) is checked in, so the viewer build
needs no shader compiler for it; rerun this after editing a shader in shaders_quasar/.
"""
import os, struct, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "indra", "newview", "vkgfx", "shaders_quasar")
OUT = os.path.join(ROOT, "indra", "newview", "vkgfx", "qlframegen_spv.h")
SHADERS = [("ql_fg_fullscreen.vert", "kQLFgFullscreenVert"), ("ql_fg_warp.frag", "kQLFgWarpFrag"),
           ("ql_fg_inputs.frag", "kQLFgInputsFrag")]

def main():
    glslang = sys.argv[1] if len(sys.argv) > 1 else "glslangValidator"
    lines = ["// Generated by scripts/quasar/build_fg_shaders.py from vkgfx/shaders_quasar. Do not edit.",
             "#pragma once", "#include <cstdint>", ""]
    for name, sym in SHADERS:
        with tempfile.TemporaryDirectory() as tmp:
            spv = os.path.join(tmp, "out.spv")
            subprocess.check_call([glslang, "-V", "--target-env", "vulkan1.2", "-o", spv, os.path.join(SRC, name)])
            data = open(spv, "rb").read()
        words = struct.unpack("<%dI" % (len(data) // 4), data)
        lines.append("static const uint32_t %s[] = {" % sym)
        for i in range(0, len(words), 8):
            lines.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
        lines.append("};")
        lines.append("")
    open(OUT, "w").write("\n".join(lines))
    print("wrote", OUT)

if __name__ == "__main__":
    main()
